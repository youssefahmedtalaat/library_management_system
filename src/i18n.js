/** Translate a shelf string such as "جناح التقنية - رف CS-12". */
export function shelfEn(shelf) {
  if (!shelf) return "";
  let out = shelf;
  for (const [ar, en] of Object.entries(shelfWingEn)) {
    out = out.split(ar).join(en);
  }
  return out.replace(/\s*[-·]\s*/g, " · ");
}

/** Build a translator bound to a language. */
export function makeT(lang) {
  const table = translations[lang] || translations.ar;
  const fallback = translations.ar;
  return function t(key, vars) {
    let str = table[key] ?? fallback[key] ?? key;
    if (vars) {
      for (const [name, value] of Object.entries(vars)) {
        str = str.split(`{${name}}`).join(String(value));
      }
    }
    return str;
  };
}
